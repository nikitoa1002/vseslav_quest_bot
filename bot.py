async def handle_ping(request):
    return web.Response(text="I am alive and ready for battle!")

async def web_server():
    app = web.Application()
    app.add_routes([web.get("/", handle_ping)])
    runner = web.AppRunner(app)
    await runner.setup()
    
    port = int(os.getenv("PORT", 8080))
    site = web.TCPSite(runner, "0.0.0.0", port)
    await site.start()
    logging.info(f"🌐 Веб-сервер запущен на порту {port}")

async def main():
    print("🚀 Квест и веб-сервер запущены!")
    
    # Запускаем веб-сервер для UptimeRobot в фоновом режиме один раз
    asyncio.create_task(web_server())
    
    # Бесконечный цикл с автопереподключением и сбросом старых зависших запросов
    while True:
        try:
            # drop_pending_updates=True сбрасывает конфликты при перезапусках на Render
            await dp.start_polling(bot, drop_pending_updates=True)
        except Exception as e:
            print(f"Обрыв связи с Telegram: {e}. Переподключение через 5 секунд...")
            await asyncio.sleep(5)

if __name__ == "__main__":
    asyncio.run(main())
