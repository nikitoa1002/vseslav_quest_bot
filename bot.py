def render_reply_keyboard(user_id: int, scene_key: str):
    builder = ReplyKeyboardBuilder()
    data = get_user_data(user_id)
    
    if scene_key == "view_chronicle":
        for topic_key in data["chronicle"]:
            raw_text = CHRONICLE_TOPICS[topic_key].split("—")[0].split(":")[0]
            clean_title = raw_text.replace("<b>", "").replace("</b>", "").strip()
            builder.button(text=f"📖 {clean_title}")
        builder.button(text="↩️ Закрыть фолиант и вернуться обратно")
        builder.adjust(1)
        return builder.as_markup(resize_keyboard=True)

    scene = STORY.get(scene_key, STORY["welcome"])
    for option in scene.get("options", []):
        if option.get("hide_if_flag") in data["flags"]: continue
        if option.get("hide_if_item") in data["inventory"]: continue
        if option.get("req_item") and option.get("req_item") not in data["inventory"]: continue
        
        if option.get("check_peasants_limit") and data.get("peasants_visited", 0) >= 3:
            continue

        req_stat = option.get("req_stat")
        if req_stat:
            stat_name, min_val = req_stat
            if data.get(stat_name, 0) < min_val: continue
        builder.button(text=option["text"])

    if scene_key not in ["welcome"] and not scene_key.startswith("fail_") and not scene_key.startswith("ending_"):
        builder.button(text="📖 Открыть древнюю Летопись Полоцка")

    builder.adjust(1)
    return builder.as_markup(resize_keyboard=True)

def format_status_panel(data: dict) -> str:
    if data["scene"] in ["welcome", "view_chronicle"] or "fail_" in data["scene"] or "react_" in data["scene"]:
        return ""
    inv_str = ", ".join(data["inventory"]) if data["inventory"] else "Пусто"
    return (
        f"\n\n⚙️ <b>БАЛАНС СИЛ И РЕСУРСОВ КНЯЖЕСТВА:</b>\n"
        f"⚔️ Дружина: <b>{data['army']}%</b> | 💰 Казна: <b>{data['gold']} з.</b>\n"
        f"⛪ Церковь: <b>{data['church']}%</b> | 🔮 Язычники: <b>{data['pagans']}%</b> | 📜 Бояре: <b>{data['boyars']}%</b>\n"
        f"🎒 <b>Инвентарь:</b> <i>{inv_str}</i>"
    )

def check_game_over(data: dict) -> str | None:
    if data["army"] <= 0: return "fail_army"
    if data["church"] <= 0: return "fail_church"
    if data["pagans"] <= 0: return "fail_pagans"
    if data["boyars"] <= 0: return "fail_boyars"
    if data["gold"] <= 0: return "fail_gold"
    return None

async def send_scene_message(message: types.Message, user_id: int, scene_key: str):
    data = get_user_data(user_id)
    scene = STORY.get(scene_key, STORY["welcome"])
    full_text = scene["text"] + format_status_panel(data)

    if scene_key.startswith("ending_"):
        total_unique_endings = 4
        unlocked_count = len(data.get("unlocked_endings", []))
        full_text += f"\n\n📊 <b>Коллекция концовок:</b> открыто <b>{unlocked_count}</b> из <b>{total_unique_endings}</b>."

    reply_markup = render_reply_keyboard(user_id, scene_key)
    photo_path = scene.get("photo", "")
    
    if photo_path and os.path.exists(photo_path):
        photo_file = FSInputFile(photo_path)
        if len(full_text) <= 1024:
            await message.answer_photo(
                photo=photo_file,
                caption=full_text,
                reply_markup=reply_markup,
                parse_mode="HTML"
            )
        else:
            await message.answer_photo(photo=photo_file)
            await message.answer(
                text=full_text,
                reply_markup=reply_markup,
                parse_mode="HTML"
            )
    else:
        await message.answer(
            text=full_text,
            reply_markup=reply_markup,
            parse_mode="HTML"
        )

